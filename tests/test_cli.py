def _make_roots(*, tmp_path, monkeypatch, roots):
    """Create each of ``roots`` in ``tmp_path``, then chdir into it."""
    for root in roots:
        if root.endswith(".md"):
            (tmp_path / root).write_text("# Title\n", encoding="utf-8")
        else:
            (tmp_path / root).mkdir()
    monkeypatch.chdir(tmp_path)


